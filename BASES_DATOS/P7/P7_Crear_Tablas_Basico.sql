

CREATE TABLE PERSONA (
    DNI        VARCHAR2(10),
    NOMBRE     VARCHAR2(50),
    TFNO       VARCHAR2(15),
    DIRECCION  VARCHAR2(100),
    POBLACION  VARCHAR2(50),
    CP         VARCHAR2(10),
    CONSTRAINT PK_DNI PRIMARY KEY (DNI)
);

CREATE TABLE ACCIONES (
    CODA           NUMBER(6),
    EMPRESA        VARCHAR2(50),
    NUMACCIONES    NUMBER(10),
    CONSTRAINT PK_CODA PRIMARY KEY (CODA)
);

CREATE TABLE INMUEBLE (
    CODI       NUMBER(6),
    METROS     NUMBER(6),
    DIRECCION  VARCHAR2(100),
    CONSTRAINT PK_CODI PRIMARY KEY (CODI)
);

CREATE TABLE PERACC (
    DNI         VARCHAR2(10),
    CODA        NUMBER(6),
    NUMACCPER   NUMBER(10) NOT NULL,
    FCOMPRACC   DATE NOT NULL,
    FVENTACC    DATE,
    CONSTRAINT PK_DNI_CODA PRIMARY KEY (DNI, CODA),
    CONSTRAINT FK_CODA FOREIGN KEY (CODA) REFERENCES ACCIONES (CODA) ON DELETE CASCADE,
    CONSTRAINT FK_DNI_ACC FOREIGN KEY (DNI) REFERENCES PERSONA (DNI) ON DELETE CASCADE
);

CREATE TABLE PERINM (
    DNI           VARCHAR2(10),
    CODI          NUMBER(6),
    PORCENTAJE    NUMBER(5,2),
    FCOMPRAINM    DATE NOT NULL,
    FVENTAINM     DATE,
    CONSTRAINT PK_DNI_CODI PRIMARY KEY (DNI, CODI),
    CONSTRAINT FK_DNI_INM FOREIGN KEY (DNI) REFERENCES PERSONA (DNI) ON DELETE CASCADE,
    CONSTRAINT FK_CODI FOREIGN KEY (CODI) REFERENCES INMUEBLE (CODI) ON DELETE CASCADE
);


ALTER TABLE INMUEBLE 
	ADD CONSTRAINT CH_METROS CHECK(METROS > 40);

ALTER TABLE ACCIONES 
	ADD CONSTRAINT CH_NUMACCIONES CHECK (NUMACCIONES > 120);

ALTER TABLE PERACC 
	ADD CONSTRAINT CH_FECHA CHECK (FCOMPRACC <= FVENTACC);

ALTER TABLE PERINM
	ADD CONSTRAINT CH_FECHA CHECK(FCOMPRAINM <= FVENTAINM );

ALTER TABLE PERINM 
	ADD CONSTRAINT CH_PORCENTAJE CHECK(PORCENTAJE  BETWEEN 10 AND 100);

ALTER TABLE ACCIONES 
	ADD CONSTRAINT UN_EMPRESA UNIQUE (EMPRESA);